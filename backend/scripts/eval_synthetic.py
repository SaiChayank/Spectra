#!/usr/bin/env python
"""Reproducible SYNTHETIC evaluation of the Spectra detector (Phase 10 / docs/33 §10.4).

Everything here is generated by ``spectra.demo`` or by this script from fixed
seeds - nothing is captured traffic - so the numbers show how the detector
behaves on *these* synthetic families, not how it performs on a real network.
Attack families are written by the same team that wrote the detector, so a high
recall on them is weak evidence; the report says so next to every table.

    cd backend
    python scripts/eval_synthetic.py --out ../docs/evidence/2026-11-06/eval-synthetic.json

Outputs one JSON document: the environment (commit, versions), the SHA-256 of
every generated capture, the model identity, and every metric with a 95 %
percentile-bootstrap interval (1000 resamples, fixed seed).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import random
import subprocess
import sys
import tempfile

import numpy as np

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BACKEND)

from spectra.demo import (  # noqa: E402
    BASE,
    _pkt,
    make_baseline_pcap,
    make_benign_diversity_pcap,
    tls_flow_packets,
    write_pcap,
)
from spectra.eval.metrics import roc_auc  # noqa: E402
from spectra.features.extractor import flows_to_matrix  # noqa: E402
from spectra.ml.model import SpectraDetector  # noqa: E402
from spectra.modules.adv.evasion import attack  # noqa: E402
from spectra.sectors import get_classifier  # noqa: E402
from spectra.tools import collect_flows  # noqa: E402

SEED = 20261106
N_BOOT = 1000


# -- synthetic attack families (hard to easy) -------------------------------------------

def _src(i: int, net: int) -> str:
    return f"10.{net}.{(i // 200) % 250}.{i % 200 + 10}"


def beacon_plain(n: int, rng: random.Random) -> list:
    """No TLS: tiny periodic records, RST end (the repo's demo beacon, varied)."""
    pkts = []
    for i in range(n):
        period = rng.choice([1.0, 2.0, 5.0, 10.0, 30.0])
        jitter = rng.uniform(0.0, 0.3)
        src, dst, sport, dport = _src(i, 66), "198.51.100.7", 41000 + i, 8443
        t, cseq, sseq = BASE + i * 400.0, 9000, 7000
        pkts += [_pkt(src, dst, sport, dport, "S", cseq, 0, t=t),
                 _pkt(dst, src, dport, sport, "SA", sseq, cseq + 1, t=t + .001),
                 _pkt(src, dst, sport, dport, "A", cseq + 1, sseq + 1, t=t + .002)]
        cseq += 1
        sseq += 1
        t += 0.002
        for _ in range(rng.randint(6, 20)):
            t += period * (1 + rng.uniform(-jitter, jitter))
            pkts.append(_pkt(src, dst, sport, dport, "PA", cseq + 1, sseq + 1,
                             b"\x00\x01\x02\x03", t=t))
            cseq += 4
            pkts.append(_pkt(dst, src, dport, sport, "PA", sseq + 1, cseq + 1,
                             b"\x00\x00", t=t + .002))
            sseq += 2
        pkts.append(_pkt(src, dst, sport, dport, "RA", cseq + 1, sseq + 1, t=t + .5))
    return pkts


def beacon_tls(n: int, rng: random.Random) -> list:
    """Hard: a normal-looking TLS session carrying tiny, slow, regular records."""
    pkts = []
    for i in range(n):
        pkts += tls_flow_packets(
            src=_src(i, 67), dst="203.0.113.77", sport=42000 + i, sni="update.example.net",
            n_data=rng.randint(8, 20), data_size=rng.randint(40, 90),
            start=BASE + i * 400.0, jitter=rng, gap_scale=rng.uniform(4.0, 14.0))
    return pkts


def exfil_bulk(n: int, rng: random.Random) -> list:
    """Hard: a TLS session moving far more data than a browsing flow."""
    pkts = []
    for i in range(n):
        pkts += tls_flow_packets(
            src=_src(i, 68), dst="203.0.113.88", sport=43000 + i, sni="storage.example.net",
            n_data=rng.randint(60, 140), data_size=rng.randint(1100, 1400),
            start=BASE + i * 400.0, jitter=rng, gap_scale=rng.uniform(0.1, 0.4))
    return pkts


def scan(n: int, rng: random.Random) -> list:
    """Easy: single-SYN probes answered by RST, one flow per target port."""
    pkts = []
    for i in range(n):
        src = _src(i // 40, 69)
        dst = f"192.0.2.{rng.randint(1, 250)}"
        dport = rng.randint(1, 65000)
        t = BASE + i * 0.5
        pkts += [_pkt(src, dst, 50000 + i % 10000, dport, "S", 1, 0, t=t),
                 _pkt(dst, src, dport, 50000 + i % 10000, "RA", 0, 2, t=t + 0.003)]
    return pkts


FAMILIES = {"beacon_plain": beacon_plain, "beacon_tls": beacon_tls,
            "exfil_bulk": exfil_bulk, "scan": scan}


# -- helpers ----------------------------------------------------------------------------------

def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def matrix(path: str) -> np.ndarray:
    return flows_to_matrix(collect_flows(path))


def boot_ci(values: np.ndarray, stat, rng: np.random.Generator) -> list[float]:
    """95 % percentile bootstrap interval of ``stat`` over resampled ``values``."""
    n = len(values)
    out = [stat(values[rng.integers(0, n, n)]) for _ in range(N_BOOT)]
    return [round(float(np.percentile(out, 2.5)), 4), round(float(np.percentile(out, 97.5)), 4)]


def rate(flags: np.ndarray, rng) -> dict:
    flags = np.asarray(flags, dtype=float)
    return {"n": int(len(flags)), "rate": round(float(flags.mean()), 4),
            "ci95": boot_ci(flags, np.mean, rng)}


def auc_with_ci(pos: np.ndarray, neg: np.ndarray, rng: np.random.Generator) -> dict:
    point = roc_auc(list(map(float, pos)), list(map(float, neg)))
    boots = []
    for _ in range(300):                       # AUC is O(n log n); 300 resamples is enough for a CI
        p = pos[rng.integers(0, len(pos), len(pos))]
        q = neg[rng.integers(0, len(neg), len(neg))]
        boots.append(roc_auc(list(map(float, p)), list(map(float, q))))
    return {"auc": round(point, 4), "ci95": [round(float(np.percentile(boots, 2.5)), 4),
                                             round(float(np.percentile(boots, 97.5)), 4)],
            "resamples": 300}


def git(*args) -> str:
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True, cwd=BACKEND,
                              check=True).stdout.strip()
    except Exception:  # noqa: BLE001
        return "unknown"


# -- the evaluation -------------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    ap.add_argument("--n-attack", type=int, default=120, help="flows per attack family")
    ap.add_argument("--n-benign", type=int, default=400)
    ap.add_argument("--evasion-sample", type=int, default=60, help="flagged flows attacked per family")
    args = ap.parse_args()

    py_rng = random.Random(SEED)
    np_rng = np.random.default_rng(SEED)
    tmp = tempfile.mkdtemp(prefix="spectra_eval_")
    files: dict[str, str] = {}

    def make(name, fn):
        path = os.path.join(tmp, f"{name}.pcap")
        fn(path)
        files[name] = path
        return path

    # baselines (training data) and held-out benign sets - different seeds from the training data
    make("train_A_demo", lambda p: make_baseline_pcap(p, n_flows=300, seed=7))
    make("train_B_diverse", lambda p: make_benign_diversity_pcap(p, n_flows=420, seed=21))
    make("val_benign", lambda p: make_benign_diversity_pcap(p, n_flows=args.n_benign, seed=501))
    make("test_benign_diverse", lambda p: make_benign_diversity_pcap(p, n_flows=args.n_benign, seed=1000))
    make("test_benign_demo", lambda p: make_baseline_pcap(p, n_flows=args.n_benign, seed=99))
    for fam, gen in FAMILIES.items():
        make(f"attack_{fam}", lambda p, g=gen: write_pcap(p, sorted(
            g(args.n_attack, py_rng), key=lambda x: float(x.time))))

    X = {name: matrix(path) for name, path in files.items()}
    result: dict = {
        "kind": "SYNTHETIC evaluation - generated traffic only; see caveats",
        "environment": {"commit": git("rev-parse", "--short", "HEAD"), "branch": git("branch", "--show-current"),
                        "python": platform.python_version(), "platform": platform.platform(),
                        "seed": SEED, "bootstrap_resamples": N_BOOT},
        "artifacts": {n: {"sha256": sha256(p), "bytes": os.path.getsize(p),
                          "flows": int(len(X[n]))} for n, p in files.items()},
        "baselines": {},
        "caveats": [
            "All traffic is synthetic. The attack families were written by the detector's authors; "
            "recall on them is weak evidence of real-world detection.",
            "The real-capture baseline from the acceptance report is not on this machine: the "
            "'two-baseline evaluation on a real capture' is NOT RUN.",
            "Precision depends on attack prevalence; it is reported at stated prevalences, not measured.",
            "Intervals are percentile bootstraps over flows; flows from one generator seed are not "
            "independent samples of a real population, so the intervals are optimistic.",
        ],
    }

    for bname, train_key in (("A_demo_baseline", "train_A_demo"), ("B_benign_diversity", "train_B_diverse")):
        det = SpectraDetector(contamination=0.02, random_state=42)
        info = det.fit(X[train_key])
        flags = {k: np.asarray(det.predict(v)).astype(bool) for k, v in X.items()}
        # ranking metrics use the RAW isolation-forest score: the 0-100 production score is a
        # percentile against the training set, clipped at 100, so it ties and cannot rank
        # anything more anomalous than the training maximum
        scores = {k: np.asarray(det._raw(v), dtype=float) for k, v in X.items()}
        # operating point from the VALIDATION benign set, never from the test sets
        thr1 = float(np.percentile(scores["val_benign"], 99.0))
        thr01 = float(np.percentile(scores["val_benign"], 99.9))
        b: dict = {"trained_on": train_key, "n_train": int(len(X[train_key])),
                   "contamination": 0.02, "score_used_for_ranking": "raw isolation-forest score (not the clipped 0-100 percentile)",
                   "model_info": {k: info.get(k) for k in ("n_train", "threshold")
                                                          if k in info},
                   "benign": {}, "attacks": {}, "operating_points": {}}
        for bk in ("test_benign_diverse", "test_benign_demo"):
            b["benign"][bk] = {"false_flag_rate": rate(flags[bk], np_rng)}
        benign_scores = scores["test_benign_diverse"]
        for fam in FAMILIES:
            k = f"attack_{fam}"
            row = {"recall_at_default_threshold": rate(flags[k], np_rng),
                   "roc_auc_vs_diverse_benign": auc_with_ci(scores[k], benign_scores, np_rng),
                   "recall_at_val_fpr_1pct": rate(scores[k] > thr1, np_rng),
                   "recall_at_val_fpr_0.1pct": rate(scores[k] > thr01, np_rng)}
            b["attacks"][fam] = row
        # precision at stated prevalences, from the pooled attack TPR and the diverse-benign FPR
        tpr = float(np.mean(np.concatenate([flags[f"attack_{f}"] for f in FAMILIES])))
        fpr = float(np.mean(flags["test_benign_diverse"]))
        b["precision_at_prevalence"] = {
            f"{int(p * 100)}%": round((tpr * p) / (tpr * p + fpr * (1 - p)), 4) if (tpr * p + fpr * (1 - p)) else None
            for p in (0.01, 0.05, 0.10, 0.50)}
        b["precision_at_prevalence"]["inputs"] = {"pooled_attack_tpr": round(tpr, 4),
                                                  "diverse_benign_fpr": round(fpr, 4)}
        b["operating_points"] = {"val_fpr_1pct_threshold": round(thr1, 3), "val_fpr_0.1pct_threshold": round(thr01, 3)}

        # adversarial robustness (the 9B attack): share of flagged attack flows that evade
        ev = {}
        for fam in FAMILIES:
            idx = np.flatnonzero(flags[f"attack_{fam}"])[: args.evasion_sample]
            if len(idx) == 0:
                ev[fam] = {"flagged_sampled": 0, "evaded": None}
                continue
            outcomes = np.array([bool(attack(det, X[f"attack_{fam}"][i], max_features=12,
                                             max_rounds=6)["evaded"]) for i in idx])
            ev[fam] = {"flagged_sampled": int(len(idx)), **{"evaded": rate(outcomes, np_rng)}}
        b["evasion_attack_default_budget"] = ev

        # cross-sector consistency: identical flow shapes, SNIs from each sector
        cls = get_classifier()
        per_sector = {}
        shapes = random.Random(SEED + 1)
        for sector, sni in (("fintech", "pay.bank.test"), ("healthcare", "portal.health.test"),
                            ("smart_city", "cdn.city.test"), ("general", "static.assets.io")):
            assert cls.classify(sni) == sector, (sni, cls.classify(sni))
            pk = []
            srng = random.Random(f"sector:{sector}")
            for i in range(args.n_benign):
                shape = shapes.getstate()
                pk += tls_flow_packets(src=_src(i, 90), sport=30000 + i, sni=sni,
                                       n_data=random.Random(f"s{i}").randint(3, 10),
                                       data_size=random.Random(f"d{i}").randint(200, 900),
                                       start=BASE + i * 2.0, jitter=srng)
                shapes.setstate(shape)
            path = os.path.join(tmp, f"sector_{sector}.pcap")
            write_pcap(path, sorted(pk, key=lambda x: float(x.time)))
            per_sector[sector] = {"sni": sni, "false_flag_rate": rate(
                np.asarray(det.predict(matrix(path))).astype(bool), np_rng)}
        rates = [v["false_flag_rate"]["rate"] for v in per_sector.values()]
        b["cross_sector_false_flags"] = {"sectors": per_sector,
                                         "max_minus_min": round(max(rates) - min(rates), 4)}
        result["baselines"][bname] = b

    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=2, sort_keys=False)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
