"""Phase 9C: synthetic-benign augmentation at train time (opt-in, default off).

Everything the augmenter adds is generated by ``spectra.demo`` - it is
SYNTHETIC and labelled so (``augmented: N`` + ``augmentation: "synthetic"`` in
the run metrics, the audit entry and the API response).  The held-out check
below uses synthetic benign traffic from the same profile families with
different seeds; it shows the mechanism works, NOT that real-network false
flags drop (no real capture is available to the test suite - see the 9C entry
in HANDOFF_PROGRESS.md).
"""

from __future__ import annotations

import json
import random

import numpy as np

from spectra.cli import build_parser
from spectra.config import Config
from spectra.demo import (
    BENIGN_PROFILES,
    make_baseline_pcap,
    make_benign_diversity_pcap,
    tls_flow_packets,
)
from spectra.features.extractor import flows_to_matrix
from spectra.pipeline import SpectraEngine
from spectra.tools import collect_flows


def _matrix(path):
    return flows_to_matrix(collect_flows(path))


def _engine(tmp_path, name):
    cfg = Config(persist=True)
    cfg.data_dir = str(tmp_path / name)
    cfg.capture_store_dir = str(tmp_path / name / "captures")
    cfg.model_path = str(tmp_path / name / "m.joblib")
    cfg.ensure_dirs()
    return SpectraEngine(config=cfg)


# -- the library -------------------------------------------------------------------

def test_library_has_at_least_five_distinct_parseable_profiles(tmp_path):
    assert len(BENIGN_PROFILES) >= 5
    means = {}
    for name in BENIGN_PROFILES:
        path = make_benign_diversity_pcap(str(tmp_path / f"{name}.pcap"), 8, seed=1,
                                          profiles=[name])
        flows = collect_flows(path)
        assert len(flows) == 8, f"{name}: expected 8 parseable flows"
        means[name] = flows_to_matrix(flows).mean(axis=0)
    # distinct behaviour, not five copies of one flow shape
    names = list(means)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            assert not np.allclose(means[a], means[b]), f"{a} == {b}"


def test_default_cadence_is_unchanged():
    a = tls_flow_packets(jitter=random.Random(3))
    b = tls_flow_packets(jitter=random.Random(3), gap_scale=1.0)
    assert [float(p.time) for p in a] == [float(p.time) for p in b]
    slow = tls_flow_packets(jitter=random.Random(3), gap_scale=10.0)
    assert float(slow[-1].time) > float(a[-1].time)


# -- augmentation at train time ----------------------------------------------------

def test_augmentation_cuts_held_out_false_flags_and_is_labelled_synthetic(tmp_path):
    baseline = make_baseline_pcap(str(tmp_path / "base.pcap"), n_flows=120, seed=7)
    held = _matrix(make_benign_diversity_pcap(str(tmp_path / "held.pcap"), 70,
                                              seed=1000))      # different seed

    plain = _engine(tmp_path, "plain")
    info0 = plain.train_from_pcap(baseline, contamination=0.02)
    aug = _engine(tmp_path, "aug")
    info1 = aug.train_from_pcap(baseline, contamination=0.02, augment=100)

    fp_plain = float(plain.model.detector.predict(held).mean())
    fp_aug = float(aug.model.detector.predict(held).mean())
    assert fp_plain - fp_aug >= 0.2, (fp_plain, fp_aug)

    assert info0["augmented"] == 0 and "augmentation" not in info0
    assert info1["augmented"] == 100 and info1["augmentation"] == "synthetic"
    assert info1["n_train"] == info0["n_train"] + 100

    entry = next(e for e in aug.audit_service.entries(limit=50)["items"]
                 if e["kind"] == "model.train")
    assert entry["payload"]["augmented"] == 100
    assert entry["payload"]["augmentation"] == "synthetic"
    runs = aug.store.model_runs(1)
    assert json.loads(runs[0]["metrics"])["augmented"] == 100


def test_augmentation_is_deterministic_and_opt_in(tmp_path):
    e = _engine(tmp_path, "d")
    assert np.array_equal(e.training.synthetic_benign(20), e.training.synthetic_benign(20))
    assert e.training.synthetic_benign(0).shape[0] == 0
    ns = build_parser().parse_args(["train", "x.pcap"])
    assert ns.augment == 0                       # off unless asked
    assert build_parser().parse_args(["train", "x.pcap", "--augment", "50"]).augment == 50


def test_api_train_augment_lands_in_model_runs(client, upload_capture, tmp_path):
    pcap = make_baseline_pcap(str(tmp_path / "api.pcap"), n_flows=60, seed=5)
    cid = upload_capture(client, pcap)["capture_id"]
    res = client.post("/api/model/train", json={"capture_id": cid, "augment": 30})
    assert res.status_code == 200, res.text
    assert res.json()["augmented"] == 30 and res.json()["augmentation"] == "synthetic"
    runs = client.get("/api/history/model-runs?limit=1").json()["items"]
    assert json.loads(runs[0]["metrics"])["augmented"] == 30
    assert client.post("/api/model/train", json={"capture_id": cid, "augment": -1}
                       ).status_code == 422
    assert client.post("/api/model/train", json={"capture_id": cid, "augment": 100000}
                       ).status_code == 422
